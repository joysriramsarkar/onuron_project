export type Category =
  | "productivity"
  | "utilities"
  | "media"
  | "games"
  | "development"
  | "communication"
  | "education"
  | "security";

export interface AppManifest {
  id: string;
  name: string;
  summary: string;
  description?: string;
  version: string;
  minOs: string;
  arch: string[];
  category: Category;
  tags?: string[];
  license?: string;
  developer: {
    name: string;
    email?: string;
    url?: string;
  };
  package: {
    url: string;
    /**
     * Repository-relative path (inside `apps/store/public`) to the committed
     * package artifact. When present the validator verifies these exact bytes
     * offline instead of downloading `url`, so CI never depends on the CDN
     * being deployed.
     */
    path?: string;
    size: number;
    sha256: string;
    /**
     * Base64-encoded Ed25519 signature over the raw package bytes.
     * Verified against the trusted publisher key identified by `signer`
     * when the validator runs with `--verify`.
     */
    signature?: string;
    /**
     * Identifier of the trusted key in `packages/store-schema/trusted-keys.json`
     * used to verify `signature`. Required when `signature` is present.
     */
    signer?: string;
  };
  media: {
    icon: string;
    screenshots?: string[];
    // Auto-generated by registry loader:
    iconUrl?: string;
    screenshotUrls?: string[];
  };
}

export const CATEGORIES: Category[] = [
  "productivity",
  "utilities",
  "media",
  "games",
  "development",
  "communication",
  "education",
  "security",
];

export const ARCHES = ["x86_64", "aarch64", "riscv64"];
