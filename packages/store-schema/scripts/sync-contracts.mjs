#!/usr/bin/env node
/**
 * sync-contracts.mjs — mirror the NilLang contract bundle into the store schema.
 *
 *   node scripts/sync-contracts.mjs [--from <dir>] [--check]
 *
 * The store's capability gate, target gate and manifest checks come from
 * NilLang, which owns them (ADR-0003, ADR-0004, ADR-0008). The store does not
 * get its own copy of the rules, because a second copy of a rule set is a second
 * answer to every question about it.
 *
 * What this does is mirror the bundle and pin it: every file is checked against
 * the SHA-256 recorded in the bundle's own index, and the result is written to
 * contracts.lock.json. The mirror is therefore provably the published contract
 * at a named bundle version, not an edited local variant.
 *
 * `--check` runs the verification without writing, which is what CI wants: it
 * fails if the mirror is missing, altered, or behind the upstream index.
 *
 * The private signing key is not involved. Nothing here reads or writes one.
 */
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";

const HERE = import.meta.dirname;
const MIRROR = path.join(HERE, "..", "contracts");
const LOCK = path.join(HERE, "..", "contracts.lock.json");

/** Files the store actually needs. The whole bundle is mirrored so that a
 *  consumer reading the lock can see what it is a subset of. */
const MIRRORED_FILES = [
  "bundle.json",
  "capabilities/vocabulary.json",
  "capabilities/requirements.json",
  "abi/runtime-abi.json",
  "nilax/manifest-v1.schema.json",
  "nilax/manifest-v2.schema.json",
];

function defaultSource() {
  if (process.env.NILLANG_CONTRACTS) return process.env.NILLANG_CONTRACTS;
  // Default layout: the ecosystem repos are siblings.
  return path.resolve(HERE, "..", "..", "..", "nilLang", "contracts");
}

function sha256(file) {
  return crypto.createHash("sha256").update(fs.readFileSync(file)).digest("hex");
}

function parseArgs(argv) {
  const args = { from: defaultSource(), check: false };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === "--from") args.from = path.resolve(argv[++i]);
    else if (argv[i] === "--check") args.check = true;
  }
  return args;
}

/**
 * Verify a mirrored bundle against the checksums in its own index.
 *
 * Returns the index on success. Throws with every problem it found otherwise,
 * because a store that cannot verify the contract it gates on must fail loudly:
 * a silently-unverified mirror is indistinguishable from a verified one at the
 * point where a package gets accepted.
 */
export function verifyMirror(dir) {
  const indexPath = path.join(dir, "bundle.json");
  if (!fs.existsSync(indexPath)) {
    throw new Error(`no contract bundle at ${dir} — run sync-contracts.mjs without --check`);
  }
  const index = JSON.parse(fs.readFileSync(indexPath, "utf8"));
  const problems = [];
  const wanted = new Set(MIRRORED_FILES);

  for (const entry of index.files ?? []) {
    const file = path.join(dir, entry.path);
    if (!fs.existsSync(file)) {
      // The store mirrors a subset of the bundle. A member outside that subset
      // is simply not here; a member inside it and absent is a broken mirror.
      if (wanted.has(entry.path)) {
        problems.push(`${entry.path} is listed in the index but missing from the mirror`);
      }
      continue;
    }
    const got = sha256(file);
    if (got !== entry.sha256) {
      problems.push(`${entry.path} checksum mismatch: index says ${entry.sha256}, mirror is ${got}`);
    }
  }

  // A file in the mirror that the index does not list is an edit the index
  // cannot vouch for, so it is as bad as a modified one.
  for (const name of wanted) {
    if (name === "bundle.json") continue;
    const listed = (index.files ?? []).some((e) => e.path === name);
    if (!listed && fs.existsSync(path.join(dir, name))) {
      problems.push(`${name} is in the mirror but not in the bundle index`);
    }
  }

  if (problems.length > 0) {
    throw new Error(`contract mirror is not the published bundle:\n  - ${problems.join("\n  - ")}`);
  }
  return index;
}

function buildLock(index, source) {
  return {
    $comment:
      "Pinned mirror of nilLang/contracts. Generated by scripts/sync-contracts.mjs; do not edit by hand. " +
      "A capability, target or package rule the store enforces is defined there, not here.",
    source: source,
    bundle: index.bundle,
    bundleVersion: index.version,
    owner: index.owner,
    files: (index.files ?? []).map((e) => ({ path: e.path, sha256: e.sha256, status: e.status })),
  };
}

function main() {
  const args = parseArgs(process.argv.slice(2));

  if (args.check) {
    const index = verifyMirror(MIRROR);
    const lock = fs.existsSync(LOCK) ? JSON.parse(fs.readFileSync(LOCK, "utf8")) : null;
    if (!lock) {
      console.error("contracts.lock.json is missing — run: node scripts/sync-contracts.mjs");
      process.exit(1);
    }
    if (lock.bundleVersion !== index.version) {
      console.error(
        `contracts.lock.json pins bundle ${lock.bundleVersion} but the mirror is ${index.version} — re-sync`
      );
      process.exit(1);
    }
    console.log(`contract mirror verified: bundle ${index.version}, ${(index.files ?? []).length} files`);
    return;
  }

  if (!fs.existsSync(path.join(args.from, "bundle.json"))) {
    console.error(
      `no contract bundle at ${args.from}\n` +
        `Pass --from <nilLang/contracts>, or set NILLANG_CONTRACTS.`
    );
    process.exit(1);
  }

  fs.rmSync(MIRROR, { recursive: true, force: true });
  for (const name of MIRRORED_FILES) {
    const from = path.join(args.from, name);
    if (!fs.existsSync(from)) {
      console.error(`upstream bundle is missing ${name}`);
      process.exit(1);
    }
    const to = path.join(MIRROR, name);
    fs.mkdirSync(path.dirname(to), { recursive: true });
    fs.copyFileSync(from, to);
  }

  // Verify what was just written rather than what was read, so a bad copy is
  // caught here instead of in a validator months from now.
  const index = verifyMirror(MIRROR);
  fs.writeFileSync(LOCK, JSON.stringify(buildLock(index, args.from), null, 2) + "\n");
  console.log(`mirrored contract bundle ${index.version} (${(index.files ?? []).length} files) into ${MIRROR}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(HERE, "sync-contracts.mjs")) {
  main();
}